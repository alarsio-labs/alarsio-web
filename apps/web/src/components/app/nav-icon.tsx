export type IconName = keyof typeof PATHS;

/** The icon for a module link, from its path ("/sites?org=…" → sites). */
export function iconForPath(path: string): IconName | null {
  const name = path.split("?")[0]?.split("/")[1] ?? "";
  return name in PATHS ? name : null;
}

export function Icon({ name, size = 18 }: { name: IconName; size?: number }) {
  return (
    <svg
      className="cx-icon"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {PATHS[name]}
    </svg>
  );
}
